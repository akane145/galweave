// deinflect.js — 日文活用还原（deinflection）—— 纯逻辑，不依赖 DOM。
//
// 解决的问题：词典按**辞书形**（原形）索引，但剧本里全是活用形。
// 查「食べた」在词典里找不到（词条是「食べる」），译者得自己在脑子里还原。
// 这一层把活用形还原成原形候选，交给词典去命中。
//
// ⚠️ 设计原则：**宁可多生成，让词典去过滤**。
//    假候选查一次词典就返回空，代价极小；而漏掉真活用才是真问题。
//    所以规则表可以宽松 —— 但必须有上限，否则候选会爆炸。
//
// ⚠️ 本模块只负责"生成候选"，**不判断哪个是正确的**。判断交给词典命中结果
//    （见 src/dict.js 的 hasDirectHit）。两者职责分离，各自可单测。
//
// 明确不做：古典/文语活用、方言、形态分析（不需要那么准，够用即可）。

/** 一次还原最多走几步（覆盖 食べさせられなかった → 4 步到 食べる） */
export const MAX_STEPS = 4;
/**
 * 最多返回几个候选。
 *
 * 实测（`tests/deinflect.test.mjs` 的规模断言）：常见活用自然产生 2–16 个候选，
 * 最深的 `食べさせられたくなかった` 是 16 个。取 20 留出余量。
 *
 * ⚠️ 这个值不能小：候选按步数升序排列，而**深层原形必然排在最后**。
 *    曾用 8，结果 `食べさせられなかった` 真正需要的 `食べる`（第 4 步）
 *    被排在前面的 8 个浅层噪音挤掉，功能等于失效。宁多查几个（假候选查空很快），
 *    也不能漏掉真原形 —— 这是本模块的核心原则。
 */
export const MAX_CANDIDATES = 20;

/* ---------------- 五段动词的段对应 ---------------- */

/**
 * 五段动词的音便规律：い段 / あ段 / え段 都指向同一个う段（辞书形）。
 * 表格式定义而非逐条硬编码 —— 九个行各写四遍规则共 36 条，手写必然出错。
 * 每行格式：[い段, あ段, う段(辞书形), え段, お段]
 */
const GODAN_ROWS = [
  ['き', 'か', 'く', 'け', 'こ'], // か行：書く
  ['ぎ', 'が', 'ぐ', 'げ', 'ご'], // が行：泳ぐ
  ['し', 'さ', 'す', 'せ', 'そ'], // さ行：話す
  ['ち', 'た', 'つ', 'て', 'と'], // た行：待つ
  ['に', 'な', 'ぬ', 'ね', 'の'], // な行：死ぬ
  ['び', 'ば', 'ぶ', 'べ', 'ぼ'], // ば行：遊ぶ
  ['み', 'ま', 'む', 'め', 'も'], // ま行：読む
  ['り', 'ら', 'る', 'れ', 'ろ'], // ら行：取る
  ['い', 'わ', 'う', 'え', 'お'], // わ行：買う（い段是「買います」的い）
];

/**
 * 规则：把 `from` 结尾换成 `to`。
 * `label` 用于给用户看（"ます形""受身"等），不参与匹配。
 * 顺序有意义：**越靠前越可能命中**，同一步数内按此顺序排序候选。
 */
function buildRules(){
  const rules = [];

  // ── 不规则动词优先 ──
  // する 必须排在「します→す」之前：否则「勉強します」会被还原成「勉強す」而不是「勉強する」。
  // 两者都会生成（宽松原则），但 する 排在前面，用户第一眼看到的是对的。
  for (const [from, to] of [
    ['します', 'する'], ['しました', 'する'], ['しません', 'する'], ['しませんでした', 'する'],
    ['しない', 'する'], ['しなかった', 'する'], ['しなくて', 'する'], ['せず', 'する'],
    ['してる', 'する'], ['している', 'する'], ['してた', 'する'], ['していた', 'する'],
    ['した', 'する'], ['して', 'する'], ['したい', 'する'], ['したくない', 'する'],
    ['すれば', 'する'], ['しろ', 'する'], ['しなさい', 'する'],
  ]) rules.push({ from, to, label: 'する' });

  for (const [from, to] of [
    ['来ます', '来る'], ['来ました', '来る'], ['来ません', '来る'],
    ['来ない', '来る'], ['来なかった', '来る'], ['来て', '来る'], ['来た', '来る'],
    ['来る', '来る'], ['来れば', '来る'], ['来い', '来る'],
    ['来られる', '来る'], ['来させる', '来る'], ['来ている', '来る'], ['来てる', '来る'],
    ['きます', 'くる'], ['きました', 'くる'], ['きません', 'くる'],
    ['こない', 'くる'], ['こなかった', 'くる'], ['きて', 'くる'], ['きた', 'くる'], ['くれば', 'くる'],
  ]) rules.push({ from, to, label: '来る' });

  // ── 补助动词：先剥补助，再靠后续规则还原实义动词 ──
  // 例：読んでいる --(でいる→で)--> 読んで --(んで→む)--> 読む（两步）
  // ⚠️ 顺序有讲究：长后缀必须排在短后缀之前，否则「てしまった」会被「て」先吃掉一半，
  //    留下「しまった」这种无法继续还原的残渣。
  for (const [from, to] of [
    ['てしまった', 'て'], ['でしまった', 'で'],
    ['てしまい', 'て'], ['でしまい', 'で'],
    ['てしまう', 'て'], ['でしまう', 'で'],
    ['ておいた', 'て'], ['でおいた', 'で'],
    ['ておいて', 'て'], ['でおいて', 'で'],
    ['ておく', 'て'], ['でおく', 'で'],
    ['てあった', 'て'], ['であった', 'で'],
    ['てあり', 'て'], ['であり', 'で'],
    ['てある', 'て'], ['である', 'で'],
    ['てほしい', 'て'], ['でほしい', 'で'],
    ['てください', 'て'], ['でください', 'で'],
    ['てくれ', 'て'], ['でくれ', 'で'],
    ['ちゃった', 'て'], ['じゃった', 'で'],
    ['ちゃう', 'て'], ['じゃう', 'で'],
    ['とく', 'て'], ['どく', 'で'],
    ['ていた', 'て'], ['でいた', 'で'],
    ['ている', 'て'], ['でいる', 'で'],
    ['てた', 'て'], ['でた', 'で'],
    ['てる', 'て'], ['でる', 'で'],
  ]) rules.push({ from, to, label: '补助动词' });

  // ── なる / する 补助（形容词与名词的常见后续）：高くなる → 高い ──
  // 放在补助动词之后、其余规则之前：它是最外层的语法标记，先剥掉才能看到实词。
  for (const [from, to] of [
    ['くなった', 'い'], ['くなる', 'い'], ['くなります', 'い'], ['くなって', 'い'],
    ['になった', 'だ'], ['になる', 'だ'], ['になります', 'だ'], ['になって', 'だ'],
  ]) rules.push({ from, to, label: 'なる补助' });

  // ── い形容词（先于五段，避免「〜く」被误当动词连用形） ──
  for (const [from, to] of [
    ['くなかった', 'い'], ['くない', 'い'], ['かった', 'い'], ['くて', 'い'],
    ['ければ', 'い'], ['く', 'い'], ['さ', 'い'], ['そう', 'い'], ['すぎる', 'い'],
  ]) rules.push({ from, to, label: 'い形容词' });

  // ── な形容词 / 名词 + 断定 ──
  for (const [from, to] of [
    ['だった', 'だ'], ['でした', 'だ'], ['です', 'だ'],
    ['じゃない', 'だ'], ['ではない', 'だ'], ['じゃなかった', 'だ'],
    ['だ', ''], ['な', ''],
  ]) rules.push({ from, to, label: '断定' });

  // ── 一段动词（る 结尾，词干不变）──
  // 这些规则与五段规则并存：例如「た」既能还原一段（食べた→食べる），
  // 也可能给五段生成一个假候选（書いた→書いる），假的无害。
  for (const [from, to] of [
    ['られる', 'る'], ['られない', 'る'], ['られた', 'る'], ['られます', 'る'],
    ['させる', 'る'], ['させない', 'る'], ['させた', 'る'], ['させます', 'る'],
    ['ない', 'る'], ['なかった', 'る'], ['なくて', 'る'], ['ないで', 'る'],
    ['ます', 'る'], ['ません', 'る'], ['ました', 'る'], ['ませんでした', 'る'],
    ['たい', 'る'], ['たくない', 'る'], ['たかった', 'る'], ['たくなかった', 'る'],
    ['れば', 'る'], ['たら', 'る'], ['ても', 'る'], ['でも', 'る'],
    ['ながら', 'る'], ['ず', 'る'], ['ぬ', 'る'],
    ['て', 'る'], ['た', 'る'], ['ろ', 'る'],
  ]) rules.push({ from, to, label: '一段' });

  // ── 五段：由段对应表生成 ──
  for (const [i, a, u, e] of GODAN_ROWS){
    // い段 + ます / たい / ながら / すぎる
    for (const [suf, label] of [
      ['ます', 'ます形'], ['ません', 'ません'], ['ました', 'ました'], ['ませんでした', 'ませんでした'],
      ['たい', 'たい'], ['たくない', 'たくない'], ['たかった', 'たかった'], ['たくなかった', 'たくなかった'],
      ['ながら', 'ながら'], ['すぎる', 'すぎる'], ['そう', 'そう'],
    ]) rules.push({ from: i + suf, to: u, label });

    // あ段 + ない / れる / せる / される（受身・使役・使役受身）
    for (const [suf, label] of [
      ['ない', 'ない形'], ['なかった', 'なかった'], ['なくて', 'なくて'], ['ないで', 'ないで'],
      ['ず', 'ず'], ['ぬ', 'ぬ'],
      ['れる', '受身'], ['れない', '受身ない'], ['れた', '受身た'], ['れます', '受身ます'],
      ['せる', '使役'], ['せない', '使役ない'], ['せた', '使役た'], ['せます', '使役ます'],
      ['される', '使役受身'], ['せられる', '使役受身'],
    ]) rules.push({ from: a + suf, to: u, label });

    // え段 + る / ば / 命令
    rules.push({ from: e + 'る', to: u, label: '可能' });
    rules.push({ from: e + 'ます', to: u, label: '可能ます' });
    rules.push({ from: e + 'ば', to: u, label: '仮定形' });
    rules.push({ from: e, to: u, label: '命令形' });
  }

  // ── 音便（て形 / た形 的促音便・撥音便・イ音便）──
  // 必须放在「て→る」「た→る」之后（更长的后缀优先，短规则兜底一段动词）。
  // ⚠️ 促音便「って」可能来自 う / つ / る / **く**（行く 是特殊促音便），
  //    四种都要给候选 —— 宁可多生成让词典过滤（本模块的核心原则）。
  for (const [suf, to] of [
    ['いて', 'く'], ['いた', 'く'],
    ['いで', 'ぐ'], ['いだ', 'ぐ'],
    ['して', 'す'], ['した', 'す'],
    ['って', 'う'], ['った', 'う'],
    ['って', 'つ'], ['った', 'つ'],
    ['って', 'る'], ['った', 'る'],
    ['って', 'く'], ['った', 'く'],
    ['んで', 'ぬ'], ['んだ', 'ぬ'],
    ['んで', 'ぶ'], ['んだ', 'ぶ'],
    ['んで', 'む'], ['んだ', 'む'],
  ]) rules.push({ from: suf, to, label: '音便' });

  return rules;
}

/** 规则表（导出供单测与 UI 展示规则覆盖范围） */
export const DEINFLECT_RULES = buildRules();

/* ---------------- 片假名折叠 ---------------- */

/**
 * 全角片假名 → 平假名。
 * 用途：不少词典按平假名索引，而外来语/强调写法用片假名（「タベタ」→「たべた」）。
 * ⚠️ 长音符「ー」（U+30FC）不在 30A1–30F6 区间内，会被保留 —— 这是对的，
 *    它是表音符号不是假名，折叠掉反而错。
 */
export function katakanaToHiragana(text){
  return String(text == null ? '' : text)
    .replace(/[\u30A1-\u30F6]/g, ch => String.fromCharCode(ch.charCodeAt(0) - 0x60));
}

/* ---------------- 主入口 ---------------- */

/**
 * 生成原形候选。
 *
 * @param {string} word 可能带活用的查询词
 * @param {{maxSteps?:number, maxCandidates?:number, foldKatakana?:boolean}} [opts]
 * @returns {Array<{word:string, steps:number, path:string[], label:string}>}
 *          按「步数少优先、规则表顺序次之」排序；**不含与输入相同的词**；
 *          无法还原时返回空数组（调用方据此不做兜底）。
 */
export function deinflect(word, opts = {}){
  const src = String(word == null ? '' : word).trim();
  if (!src) return [];
  const maxSteps = Number.isFinite(opts.maxSteps) && opts.maxSteps > 0 ? Math.floor(opts.maxSteps) : MAX_STEPS;
  const maxCand = Number.isFinite(opts.maxCandidates) && opts.maxCandidates > 0 ? Math.floor(opts.maxCandidates) : MAX_CANDIDATES;
  const foldKatakana = opts.foldKatakana !== false;   // 默认开启

  /** 每个候选词保留**步数最少**的那条路径（供 UI 显示与排序） */
  const best = new Map();
  /**
   * 已被展开过的（词, 步数）：防止同一步数内重复展开同一词导致指数爆炸。
   *
   * ⚠️ 为什么键里必须带**步数**：同一个词可能在不同深度出现，而更深的那个可能
   *    通向更长的还原链。曾用「词已出现就跳过」的写法，结果
   *    `食べさせられなかった` 因为「食べさせられない」在第 1 步就被收录并停止展开，
   *    再也不会从它继续剥到 `させる → る`，最终**漏掉真正的原形**。
   *    键里带步数后，浅层与深层各自展开一次，既不丢链也不爆炸。
   */
  const expanded = new Set();
  let frontier = [{ word: src, path: [src] }];

  for (let step = 1; step <= maxSteps && frontier.length; step++){
    const next = [];
    for (const node of frontier){
      const key = node.word + '\u0000' + step;
      if (expanded.has(key)) continue;
      expanded.add(key);

      for (let ri = 0; ri < DEINFLECT_RULES.length; ri++){
        const rule = DEINFLECT_RULES[ri];
        if (!node.word.endsWith(rule.from)) continue;
        const stem = node.word.slice(0, node.word.length - rule.from.length);
        const candidate = stem + rule.to;
        if (!candidate || candidate === src) continue;      // 空串或绕回原词
        const path = [...node.path, candidate];
        const prev = best.get(candidate);
        if (!prev || step < prev.steps){
          best.set(candidate, { word: candidate, steps: step, path, label: rule.label, order: ri });
        }
        next.push({ word: candidate, path });
      }
    }
    frontier = next;
  }

  // 排序：**先按"是否可能是有意义的长词"**，再按步数。
  // 直接按步数升序会让「食べたくなかった」的 8 个名额全被第 1 步的噪音占满，
  // 真正需要的深层原形反而排不进来。所以先按步数分组，组内按规则表顺序。
  const out = [...best.values()].sort((a, b) => a.steps - b.steps || a.order - b.order);

  // 片假名折叠：作为一个额外候选追加（不是替换），因为原文可能本身就是片假名词条
  if (foldKatakana){
    const hira = katakanaToHiragana(src);
    if (hira !== src){
      out.push({ word: hira, steps: 1, path: [src, hira], label: '片假名转平假名', order: Number.MAX_SAFE_INTEGER });
      // 折叠后再走一遍规则，覆盖「タベタ」这类整句片假名的活用
      for (const extra of deinflect(hira, { ...opts, foldKatakana: false, maxCandidates: maxCand })){
        if (extra.word !== src && !best.has(extra.word)){
          out.push({ ...extra, steps: extra.steps + 1, path: [src, ...extra.path], label: '片假名转平假名·' + extra.label });
          best.set(extra.word, extra);
        }
      }
    }
  }

  return out.slice(0, maxCand);
}

/**
 * 由候选与命中词反推「为什么是这个原形」，供 UI 显示。
 * @returns {string} 形如 `食べたくなかった → 食べたい → 食べる`；无路径时返回空串
 */
export function describePath(candidate){
  const path = candidate && Array.isArray(candidate.path) ? candidate.path : null;
  if (!path || path.length < 2) return '';
  return path.join(' → ');
}
